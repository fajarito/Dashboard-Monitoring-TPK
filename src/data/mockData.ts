const bogorWeights = bogorSubdistrictCatalog.map(
  (_, index) => 10 + ((index * 7) % 17),
)

const allocateBogorTotal = (total: number) => {
  const weightTotal = bogorWeights.reduce((sum, weight) => sum + weight, 0)
  const rawValues = bogorWeights.map((weight) => (total * weight) / weightTotal)
  const values = rawValues.map(Math.floor)
  let remainder = total - values.reduce((sum, value) => sum + value, 0)
  rawValues
    .map((value, index) => ({ index, fraction: value - Math.floor(value) }))
    .sort((first, second) => second.fraction - first.fraction)
    .forEach(({ index }) => {
      if (remainder > 0) {
        values[index] += 1
        remainder -= 1
      }
    })
  return values
}

